"""Builds public/ek/ek.js (the prototype's views, carved to run inside the Astro pages) and public/ek/D.json (its data).

  python3 tools/ek/build_ek.py            from app/site, after ./run_pipeline.sh has refreshed src/data/*.json
Sources: src/ek/*.js (the v8 prototype, patched here), data from src/data/*.json and public/projects.json (tools/ek/repo_to_D.py).
The English dictionary src/ek/i18n-en.js is generated by tools/ek/i18n/gen.py (not needed to rebuild the bundle).
"""
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.abspath(os.path.join(HERE, '..', '..'))
SRC, OUT = os.path.join(SITE, 'src', 'ek'), os.path.join(SITE, 'public', 'ek')
os.makedirs(OUT, exist_ok=True)

# ---- data: the exports of the site in the shape the views expect, plus the county outlines
dpath = os.path.join(OUT, 'D.json')
subprocess.run([sys.executable, os.path.join(HERE, 'repo_to_D.py'), SITE, dpath], check=True)
D = json.load(open(dpath, encoding='utf-8'))
D['geo'] = json.load(open(os.path.join(HERE, 'geo.json'), encoding='utf-8'))
open(dpath, 'w', encoding='utf-8').write(json.dumps(D, ensure_ascii=False, separators=(',', ':')))


def rd(f):
    return open(os.path.join(SRC, f), encoding='utf-8').read()


def sub(src, a, b, name):
    if a not in src:
        sys.exit(f'GREŠKA: u {name} nema mjesta za zamjenu: {a[:70]!r} (prototip se promijenio?)')
    return src.replace(a, b, 1)


core = rd('core.js')
core = sub(core, 'const D = /*__DATA__*/null;\nD.geo = /*__GEO__*/null;', 'const D = window.__EK_D;', 'core.js')
core = sub(core, "let LANG = 'hr';", "let LANG = document.documentElement.lang === 'en' ? 'en' : 'hr';", 'core.js')
# the prototype builds its own sidebar and wires its own menu here; the Astro layout does that
a, b = core.index('/* [ključ odjeljka'), core.index('/* ============ zajednički gradivni blokovi')
core = core[:a] + core[b:]
i18n = rd('i18n.js')
i18n = sub(i18n, "if (l === 'hr') toHR(document.body);", "if (l === 'hr') toHR(VIEWROOT());", 'i18n.js')
i18n = sub(i18n, "if (l === 'en') toEN(document.body);", "if (l === 'en') toEN(VIEWROOT());", 'i18n.js')
i18n = sub(i18n, "obs.observe(document.body,", "obs.observe(VIEWROOT(),", 'i18n.js')
i18n = sub(i18n, "function collect(root = document.body)", "function collect(root = VIEWROOT())", 'i18n.js')
i18n = sub(i18n, "    const y = window.scrollY, navOpen = document.body.classList.contains('navopen');\n    if (typeof paintDate === 'function') paintDate();\n    if (typeof route === 'function') route();\n    window.scrollTo(0, y); if (navOpen) setNav(true);\n", '', 'i18n.js')
i18n = sub(i18n, "    $$('.lang button').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === l)));\n", '', 'i18n.js')
i18n = sub(i18n, "const I18N = (() => {", "const VIEWROOT = () => document.getElementById('view') || document.body;\nconst I18N = (() => {", 'i18n.js')
views2 = sub(rd('views2.js'), "new MutationObserver(enhSoon).observe($('#view'),", "if ($('#view')) new MutationObserver(enhSoon).observe($('#view'),", 'views2.js')
views2 = sub(views2, "$('#view').addEventListener('change', enhSoon); $('#view').addEventListener('input', enhSoon);", "if ($('#view')) { $('#view').addEventListener('change', enhSoon); $('#view').addEventListener('input', enhSoon); }", 'views2.js')
parts = [core, rd('ui.js'), rd('export.js'), i18n, rd('i18n-en.js'), rd('views.js'), views2, rd('heromap.js'), rd('hero.js'), rd('pages.js'), rd('assistant.js'), rd('engine.js')]
bundle = '(function(){\n"use strict";\n' + '\n'.join(parts) + '\n})();\n'
open(os.path.join(OUT, 'ek.js'), 'w', encoding='utf-8').write(bundle)
print(f'public/ek/ek.js {len(bundle) // 1024} KB, D.json {os.path.getsize(dpath) // 1024} KB')

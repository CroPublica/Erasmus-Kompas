import re, shutil, unicodedata


def slug(s):
    s = unicodedata.normalize('NFD', str(s))
    s = ''.join(ch for ch in s if not unicodedata.combining(ch)).replace('đ', 'd').replace('Đ', 'D').lower()
    return re.sub(r'^-|-$', '', re.sub(r'[^a-z0-9]+', '-', s))


